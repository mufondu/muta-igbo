const BY_KEY = new Map<string, PictureEntry>(
  PICTURE_REGISTRY.map(e => [pictureKey(e.igbo, e.english), e]),
);

export function getPictureEntry(igbo: string, english: string): PictureEntry | undefined {
  return BY_KEY.get(pictureKey(igbo, english));
}

/** Asset key to show for this exact pair, or undefined when no approved picture exists. */
export function getApprovedAsset(igbo: string, english: string): string | undefined {
  const e = getPictureEntry(igbo, english);
  return e && e.status === "approved" ? e.asset : undefined;
}

/** True when the pair has an approved picture AND is cleared for games. */
export function isGamePicture(igbo: string, english: string): boolean {
  const e = getPictureEntry(igbo, english);
  return !!e && e.status === "approved" && !!e.asset && !!e.game;
}
