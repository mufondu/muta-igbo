// Reviewed picture registry. ONE source of truth for which picture goes with which word.
//
// A picture is shown ONLY when an entry for the exact Igbo + English pair has status "approved".
// There is no keyword or substring guessing, so "Good morning" can never get a walking picture.
//
// status:
//   approved   picture is correct for this exact word (shown in lessons and games)
//   replace    a picture exists but is wrong or weak; NOT shown until replaced
//   needs_art  a concrete word with no picture file yet; NOT shown
//   text_only  abstract word, letter, number, phrase or sentence; shown as text or its own emoji
// game: true  also eligible for Picture Match and Listen & Tap (clear, single-word, unambiguous)
//
// To approve a new picture: add its file in customManifest.ts, then set status "approved" and
// asset here. Regenerate docs/picture-review.html with scripts/build_picture_review.py.

export type PictureStatus = "approved" | "replace" | "needs_art" | "text_only";

export interface PictureEntry {
  igbo: string;
  english: string;
  status: PictureStatus;
  asset?: string; // key in CUSTOM_ILLUSTRATIONS
  game?: boolean;
  note?: string;
}

export function pictureKey(igbo: string, english: string): string {
  const n = (v: string) =>
    (v || "")
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[^\w\s-]/g, "")
      .replace(/\s+/g, " ")
      .trim();
  return n(igbo) + "|" + n(english);
}

